  // Attache à FOOD_CALC._DB si dispo, sinon expose pour merge ultérieur
  function mergeWhenReady() {
    if (window.FOOD_CALC && Array.isArray(window.FOOD_CALC._DB)) {
      window.FOOD_CALC._DB = window.FOOD_CALC._DB.concat(EXTRA_FOODS);
      window.FOOD_CALC._extended = true;
      return true;
    }
    return false;
  }

  if (!mergeWhenReady()) {
    // extras.js peut charger après : retente au DOMContentLoaded + fallback timer
    document.addEventListener('DOMContentLoaded', function() {
      if (!mergeWhenReady()) {
        var tries = 0;
        var iv = setInterval(function() {
          if (mergeWhenReady() || ++tries > 40) clearInterval(iv);
        }, 100);
      }
    });
  }

  // Expose globalement pour debug
  window._EXTRA_FOODS = EXTRA_FOODS;
