  function getPortions(name) {
    if (!name) return null;
    var k = _normalize(name);
    if (FOOD_PORTIONS[k]) return FOOD_PORTIONS[k];
    // Fallback : essayer variantes (sans parenthèses, sans suffixe entre parenthèses)
    var noParen = k.replace(/\s*\([^)]*\)\s*/g, ' ').replace(/\s+/g, ' ').trim();
    if (noParen !== k && FOOD_PORTIONS[noParen]) return FOOD_PORTIONS[noParen];
    return null;
  }

  function getDefaultPortion(name) {
    var p = getPortions(name);
    if (p && p.length) return p[0];
    return null;
  }

